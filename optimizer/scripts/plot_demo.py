import os
import sys

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
from aco_vrp import ACOParams, solve_vrp  # noqa: E402

SEED, VEHICLES, CAPACITY = 3, 3, 70
DEPOT = {"name": "Depot", "x": 77.6, "y": 12.9, "demand": 0}
STOPS = [  # approximate Bengaluru neighbourhood centres
    ("Koramangala", 77.6245, 12.9352, 20), ("Indiranagar", 77.6408, 12.9784, 15),
    ("Whitefield", 77.75, 12.9698, 25), ("Electronic City", 77.677, 12.8452, 30),
    ("Jayanagar", 77.5838, 12.925, 10), ("Malleshwaram", 77.57, 13.0035, 15),
    ("Hebbal", 77.597, 13.0358, 20), ("Marathahalli", 77.6974, 12.9591, 15),
    ("HSR Layout", 77.6412, 12.9116, 20), ("Yelahanka", 77.5963, 13.1007, 25),
]
locs = [DEPOT] + [{"name": n, "x": x, "y": y, "demand": d} for n, x, y, d in STOPS]
res = solve_vrp(locs, VEHICLES, capacity=CAPACITY, params=ACOParams(seed=SEED))
COLORS = ["#2563eb", "#db2777", "#d97706", "#7c3aed"]


def draw(ax, routes, title):
    for k, r in enumerate(routes):
        xs, ys = [locs[i]["x"] for i in r], [locs[i]["y"] for i in r]
        ax.plot(xs, ys, color=COLORS[k % 4], lw=2.2, zorder=2)
        for a, b in zip(r[:-1], r[1:]):
            ax.annotate("", xy=(locs[b]["x"], locs[b]["y"]), xytext=(locs[a]["x"], locs[a]["y"]),
                        arrowprops=dict(arrowstyle="->", color=COLORS[k % 4], lw=1.6), zorder=3)
    for i, l in enumerate(locs):
        ax.scatter(l["x"], l["y"], s=90 if i == 0 else 45, marker="s" if i == 0 else "o",
                   color="#1d4ed8" if i == 0 else "#ef4444", zorder=4, edgecolor="white")
        ax.annotate(l["name"], (l["x"], l["y"]), textcoords="offset points", xytext=(6, 6), fontsize=7)
    ax.set_title(title, fontsize=11, fontweight="bold")
    ax.set_xticks([]); ax.set_yticks([])


fig, axes = plt.subplots(1, 3, figsize=(16, 5.2), gridspec_kw={"width_ratios": [1, 1, 0.9]})
b = res["baseline"]
missed = f", misses {len(b['unserved'])} stop(s)" if b["unserved"] else ""
draw(axes[0], b["routes"], f"Baseline: stops in input order\n{b['distance_km']} km{missed}")
draw(axes[1], res["routes"], f"Ant Colony Optimization ({res['improvement_pct']}% shorter)\n{res['distance_km']} km")
axes[2].plot(range(1, len(res["convergence"]) + 1), res["convergence"], color="#2563eb", lw=2)
axes[2].set_title("Colony convergence", fontsize=11, fontweight="bold")
axes[2].set_xlabel("Iteration"); axes[2].set_ylabel("Best total distance (km)")
axes[2].spines[["top", "right"]].set_visible(False)
fig.text(0.5, 0.01, f"{VEHICLES} vehicles, capacity {CAPACITY}, {len(STOPS)} stops in Bengaluru. "
         f"Generated by optimizer/scripts/plot_demo.py (seed {SEED}).", ha="center", fontsize=9, color="#555")
fig.tight_layout(rect=(0, 0.04, 1, 1))
out = os.path.join(os.path.dirname(__file__), "..", "..", "docs", "solver-comparison.png")
fig.savefig(out, dpi=110)
print(f"baseline {b['distance_km']} km -> ACO {res['distance_km']} km ({res['improvement_pct']}% shorter), unserved={res['unserved']}")
